def _format_cards_text(spread: list[dict]) -> str:
    parts = []

    for index, item in enumerate(spread, start=1):
        card = item["card"]
        position = item["position"]

        orientation = (
            "прямая"
            if not card["reversed"]
            else "перевёрнутая"
        )

        parts.append(
            f"""
Карта {index}
Позиция: {position}
Название: {card["name"]}
Аркан: {card["arcana"]}
Масть: {card["suit"] or "нет"}
Положение: {orientation}
Значение: {card["meaning"]}
"""
        )

    return "".join(parts)


def trim_truncated(text: str) -> str:
    """
    Ответ упёрся в лимит токенов: убираем недописанный хвост,
    чтобы текст не обрывался на полуслове.
    """

    text = text.rstrip()

    paragraph_end = text.rfind("\n\n")

    if paragraph_end > len(text) * 0.6:
        text = text[:paragraph_end]
    else:
        sentence_end = max(
            text.rfind(". "),
            text.rfind("! "),
            text.rfind("? "),
            text.rfind(".\n")
        )

        if sentence_end > len(text) * 0.6:
            text = text[:sentence_end + 1]

    return (
        text.rstrip()
        + "\n\n(Интерпретация получилась длиннее лимита "
        "и была сокращена.)"
    )


def _call_llm(
    system_prompt: str,
    prompt: str,
    max_tokens: int,
    max_retries: int = 3
) -> str:

    for attempt in range(max_retries):
        try:
            response = client.chat.completions.create(
                model="ai-sage/GigaChat3.5-432B-A28B",
                max_tokens=max_tokens,
                temperature=0.7,
                presence_penalty=0,
                top_p=1,
                messages=[
                    {
                        "role": "system",
                        "content": system_prompt
                    },
                    {
                        "role": "user",
                        "content": prompt
                    }
                ]
            )
            break

        except RETRYABLE_ERRORS as error:
            if attempt == max_retries - 1:
                raise

            wait_time = 2 ** attempt

            logger.warning(
                "Cloud.ru временно недоступен (%s). "
                "Повтор через %s сек. Попытка %s/%s",
                error,
                wait_time,
                attempt + 1,
                max_retries
            )

            time.sleep(wait_time)

    result = response.choices[0].message.content

    if not result:
        raise ValueError(
            "Cloud.ru вернул пустой ответ"
        )

    finish_reason = response.choices[0].finish_reason

    if finish_reason == "length":
        logger.warning(
            "Ответ LLM обрезан по max_tokens (%s)",
            max_tokens
        )

        result = trim_truncated(result)

    return result


def interpret_tarot(
    question: str,
    spread_name: str,
    spread: list[dict]
) -> str:

    cards_text = _format_cards_text(spread)

    spread_instructions = get_spread_instructions(
        spread_name
    )

    spread_title = SPREADS[spread_name]["name"]

    if len(spread) == 1:
        output_instruction = """
Для одной карты дай 3 содержательных абзаца.
Не используй заголовок и отдельное заключение.
"""
        max_tokens = 700
    else:
        output_instruction = """
Для нескольких карт:
1. интерпретируй позиции;
2. покажи связи и противоречия между картами;
3. сформулируй общую динамику;
4. вернись к исходному вопросу и дай главный вывод.

Не повторяй одну мысль несколько раз.
"""
        max_tokens = min(2800, 500 + len(spread) * 150)

    prompt = f"""
Вопрос пользователя:
{question}

Название расклада:
{spread_title}

Специальные правила этого расклада:
{spread_instructions}

Карты расклада:
{cards_text}

Прочитай этот расклад именно как ответ
на вопрос пользователя.

{output_instruction}

Не добавляй ничего кроме готовой интерпретации.
"""

    return _call_llm(
        SYSTEM_PROMPT,
        prompt,
        max_tokens
    )


