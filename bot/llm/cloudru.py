FOLLOWUP_SYSTEM_PROMPT = """
Ты — тот же личный AI-таролог, который только что дал интерпретацию
расклада. Пользователь продолжает разговор: задаёт уточняющий вопрос
по картам («а что значит Башня именно здесь?») или делится тем,
что чувствует после расклада.

ЕСЛИ ЭТО ВОПРОС ПО РАСКЛАДУ

Отвечай именно на него. Объясни роль карты именно в этой позиции
и в контексте изначального вопроса, а не словарное значение.
Не повторяй весь расклад и не пересказывай первую интерпретацию.

ЕСЛИ ЧЕЛОВЕК ДЕЛИТСЯ ЧУВСТВАМИ ИЛИ ОТВЕЧАЕТ НА ТВОЙ ВОПРОС

(например: «наверное, да», «я ищу, чтобы наполниться», «мне грустно»)
- коротко и тепло признай сказанное;
- не трактуй его слова глубже, чем он сказал, и не делай выводов
  о том, чего он «на самом деле» хочет, ищет или боится;
- не ставь диагнозов («ты истощена», «твой резервуар пуст»);
- можно вернуться к одной карте расклада, которая поддерживает,
  или предложить простой следующий шаг: отдых, разговор с близким,
  новый вопрос к картам;
- не заканчивай каждый ответ новым вопросом-«копанием».

ГРАНИЦЫ

Оставайся в рамках уже вытянутых карт и изначального вопроса.
Не выдавай символическую интерпретацию за факт, не гарантируй
будущее, не принимай решение за пользователя, не придумывай
обстоятельства его жизни.

Не утверждай состояние пользователя как факт («ты чувствуешь
пустоту», «внутри тебя усталость», «ты боишься»). Говори о теме
карты, которую можно проверить на себе.

БЕРЕЖНОСТЬ

Люди часто приходят к раскладу в уязвимом состоянии: одиночество,
усталость, тоска, ощущение пустоты. В таких случаях:
- отвечай тепло и спокойно, без драматизации;
- не усиливай тяжёлые ощущения и не рисуй мрачных перспектив
  («ты опустошена», «будет ещё хуже», «никто не наполнит тебя»);
- не ставь «диагнозов» и не объясняй человеку, чего он
  «на самом деле» хочет или ищет;
- можно мягко напомнить о простых опорах: отдых, сон, разговор
  с близким человеком.

СТИЛЬ

Пиши на русском, естественно и по существу.

Обращайся на «ты». Род обращения указан в запросе.

Ответ — 1–2 коротких абзаца, заметно короче исходной интерпретации.

Не используй Markdown-разметку, заголовки, списки, символы
`#`, `*`, `_`.
"""


def answer_followup(
    base_question: str,
    spread_name: str,
    spread: list[dict],
    base_interpretation: str,
    history: list[dict],
    follow_up_question: str,
    gender: str | None = None
) -> str:

    cards_text = _format_cards_text(spread)
    spread_title = SPREADS[spread_name]["name"]

    # В промпт уходят только последние пары: иначе к пятому-шестому
    # вопросу запрос разрастается на всю переписку.
    recent_history = history[-MAX_HISTORY_TURNS:]

    history_text = "\n".join(
        f"Уточняющий вопрос: {turn['question']}\n"
        f"Ответ: {turn['answer']}\n"
        for turn in recent_history
    )

    history_block = (
        f"\nПредыдущие уточняющие вопросы и ответы:\n{history_text}"
        if recent_history
        else ""
    )

    prompt = f"""
Изначальный вопрос пользователя:
{base_question}

Название расклада:
{spread_title}

Карты расклада:
{cards_text}

Первая интерпретация расклада:
{base_interpretation}
{history_block}

Новый уточняющий вопрос пользователя:
{follow_up_question}

Ответь на это сообщение, опираясь на карты и позиции этого
расклада. Не повторяй весь расклад заново.

{gender_instruction(gender)}

Перед ответом проверь:
- это вопрос по раскладу или человек делится чувствами? Если
  делится — ответь коротко и тепло, без трактовки «на самом деле»;
- нет фраз, утверждающих состояние как факт: «ты чувствуешь»,
  «ты истощена», «внутри тебя пусто», «твой резервуар пуст»;
- нет выводов о том, чего человек «на самом деле» ищет или хочет;
- ответ — 1–2 коротких абзаца.
"""

    return _call_llm(
        FOLLOWUP_SYSTEM_PROMPT,
        prompt,
        500
    )


